<script lang="ts">
  // The official Form 1301 pages with the year's values placed on them (old web/src/views/Print.svelte, mode "form").
  // Page images and box positions ship with the IL pack (packages/countries/il/form), extracted from the official PDF by layout.py.
  // A fixed Hebrew form: marks are placed with physical left offsets, independent of the interface direction.
  import { page } from "$app/state";
  import { S, fmt } from "#lib/stores/books.svelte.ts";
  import { t } from "#lib/i18n.svelte.ts";
  import { Button } from "#lib/ui/index.ts";
  import { ilYear } from "../../../tax/il/il.ts";
  import layoutJson from "@openbooks/country-il/form/layout.json";
  import p1 from "@openbooks/country-il/form/p-1.png";
  import p2 from "@openbooks/country-il/form/p-2.png";
  import p3 from "@openbooks/country-il/form/p-3.png";
  import p4 from "@openbooks/country-il/form/p-4.png";
  import { marks, type Layout } from "./marks.ts";
  import "../../print.css";

  const TEMPLATE_YEAR = 2025;
  const year = $derived(+page.params.year! || S.year);
  const b = $derived(S.data ? ilYear(year) : null);
  const layout = layoutJson as unknown as Layout; // generated by layout.py; JSON widens the tuple and enum types
  const pages = [p1, p2, p3, p4];
</script>

<svelte:head><title>1301 · {year} · OpenBooks</title></svelte:head>

<div class="ob-print">
  <div class="ob-print-bar"><Button variant="primary" icon="printer" onclick={() => print()}>{t("print.button")}</Button></div>
  {#if b}
    {#if year !== TEMPLATE_YEAR}
      <div class="mx-auto mb-3 max-w-[595pt] rounded-lg border border-warn/40 bg-warn/10 px-4 py-2.5 text-[12px] text-ink" role="note">
        {t("legal.printTemplateNotice", { y: year, tpl: TEMPLATE_YEAR, rates: b.T.year })}
      </div>
    {/if}
    <div class="form-scroll" dir="rtl" lang="he">
      {#each pages as img, n (img)}
        <div class="form-page" style:width="{layout.size[0]}pt" style:height="{layout.size[1]}pt" style:background-image="url({img})">
          {#each marks(layout, n + 1, b.v) as mk, i (i)}
            <span class="mk {mk.cls}" dir={mk.cls === "txt" ? "auto" : undefined} style={mk.style}>{mk.text}</span>
          {/each}
        </div>
      {/each}
    </div>
    {#if b.foreignHoldings.length || b.f1324.income || b.unresolvedHoldings.length || b.missingFx.length}
      <section class="mx-auto mt-6 max-w-[595pt] rounded-lg border border-line bg-panel p-5 text-[13px] text-ink" style="page-break-before: always;">
        <h2 class="text-[15px] font-medium">{t("legal.printCrossBorderTitle", { y: year })}</h2>
        <p class="mt-1 text-[12px] text-sub">{t("legal.printCrossBorderSub")}</p>
        {#if b.unresolvedHoldings.length}
          <p class="mt-3 rounded border border-warn/40 bg-warn/10 px-3 py-2 text-[12px] text-warn">
            {t("legal.unresolvedBanner", { n: b.unresolvedHoldings.length })}
          </p>
        {/if}
        {#if b.missingFx.length}
          <p class="mt-3 rounded border border-warn/40 bg-warn/10 px-3 py-2 text-[12px] text-warn">
            {t("legal.f1324NoRate", { cur: [...new Set(b.missingFx.map((m) => m.currency))].join(", "), n: b.missingFx.length })}
          </p>
        {/if}
        <dl class="mt-3 divide-y divide-line">
          <div class="flex justify-between py-1.5"><dt class="text-sub">{t("legal.ret.foreign")}</dt><dd class="num">{fmt(b.f1324.income)}</dd></div>
          <div class="flex justify-between py-1.5"><dt class="text-sub">{t("legal.printForeignTax")}</dt><dd class="num">{fmt(b.f1324.taxPaid)}</dd></div>
          <div class="flex justify-between py-1.5"><dt class="text-sub">{t("legal.ret.ftc")}</dt><dd class="num">{fmt(b.f1324.credit)}</dd></div>
          <div class="flex justify-between py-1.5"><dt class="text-sub">{t("legal.printForm150Count")}</dt><dd class="num">{b.foreignHoldings.length}</dd></div>
        </dl>
      </section>
    {/if}
  {/if}
</div>
